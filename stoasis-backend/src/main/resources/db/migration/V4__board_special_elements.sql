CREATE TABLE pin_stacks (
    id VARCHAR(64) PRIMARY KEY,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    grid_x INTEGER NOT NULL,
    grid_y INTEGER NOT NULL,
    height_clips INTEGER NOT NULL,
    layer INTEGER NOT NULL,
    expanded BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_pin_stacks_x CHECK (grid_x BETWEEN 0 AND 144),
    CONSTRAINT chk_pin_stacks_y CHECK (grid_y BETWEEN 0 AND 239),
    CONSTRAINT chk_pin_stacks_height CHECK (height_clips BETWEEN 1 AND 240),
    CONSTRAINT chk_pin_stacks_layer CHECK (layer >= 0)
);

CREATE TABLE pin_stack_children (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stack_id VARCHAR(64) NOT NULL REFERENCES pin_stacks(id) ON DELETE CASCADE,
    pin_id VARCHAR(64) NOT NULL REFERENCES pins(id) ON DELETE CASCADE,
    child_order INTEGER NOT NULL,
    original_x INTEGER NOT NULL,
    original_y INTEGER NOT NULL,
    original_layer INTEGER NOT NULL,
    CONSTRAINT uk_pin_stack_child UNIQUE (pin_id),
    CONSTRAINT uk_pin_stack_order UNIQUE (stack_id, child_order)
);

CREATE TABLE board_connectors (
    id VARCHAR(64) PRIMARY KEY,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    source_pin_id VARCHAR(64) NOT NULL REFERENCES pins(id) ON DELETE CASCADE,
    target_pin_id VARCHAR(64) NOT NULL REFERENCES pins(id) ON DELETE CASCADE,
    color_variant VARCHAR(24) NOT NULL,
    CONSTRAINT chk_connector_distinct CHECK (source_pin_id <> target_pin_id),
    CONSTRAINT uk_board_connector UNIQUE (collection_id, source_pin_id, target_pin_id)
);

CREATE TABLE soft_zones (
    id VARCHAR(64) PRIMARY KEY,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    grid_x INTEGER NOT NULL,
    grid_y INTEGER NOT NULL,
    width_clips INTEGER NOT NULL,
    height_clips INTEGER NOT NULL,
    color_variant VARCHAR(24) NOT NULL,
    label VARCHAR(80),
    CONSTRAINT chk_soft_zones_geometry CHECK (
        grid_x >= 0 AND grid_y >= 0 AND width_clips >= 2 AND height_clips >= 2
    )
);

CREATE TABLE floating_labels (
    id VARCHAR(64) PRIMARY KEY,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    grid_x INTEGER NOT NULL,
    grid_y INTEGER NOT NULL,
    width_clips INTEGER NOT NULL,
    text VARCHAR(120) NOT NULL,
    layer INTEGER NOT NULL,
    CONSTRAINT chk_floating_labels_geometry CHECK (
        grid_x >= 0 AND grid_y >= 0 AND width_clips BETWEEN 2 AND 6 AND layer >= 0
    )
);

CREATE TABLE stickers (
    id VARCHAR(64) PRIMARY KEY,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    position_x DOUBLE PRECISION NOT NULL,
    position_y DOUBLE PRECISION NOT NULL,
    width_clips DOUBLE PRECISION NOT NULL,
    height_clips DOUBLE PRECISION NOT NULL,
    rotation DOUBLE PRECISION NOT NULL,
    layer INTEGER NOT NULL,
    motif VARCHAR(40) NOT NULL,
    color_variant VARCHAR(24) NOT NULL,
    CONSTRAINT chk_sticker_size CHECK (
        width_clips BETWEEN 2 AND 8 AND height_clips BETWEEN 2 AND 8
    ),
    CONSTRAINT chk_sticker_rotation CHECK (rotation BETWEEN -15 AND 15),
    CONSTRAINT chk_sticker_layer CHECK (layer >= 0)
);

CREATE INDEX idx_pin_stacks_collection_layer ON pin_stacks(collection_id, layer);
CREATE INDEX idx_pin_stack_children_stack ON pin_stack_children(stack_id, child_order);
CREATE INDEX idx_board_connectors_collection ON board_connectors(collection_id);
CREATE INDEX idx_soft_zones_collection ON soft_zones(collection_id);
CREATE INDEX idx_floating_labels_collection ON floating_labels(collection_id);
CREATE INDEX idx_stickers_collection_layer ON stickers(collection_id, layer);
