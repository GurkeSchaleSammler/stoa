CREATE TABLE worlds (
    id VARCHAR(64) PRIMARY KEY,
    owner_id VARCHAR(64) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(180) NOT NULL,
    emoji VARCHAR(32) NOT NULL,
    visibility VARCHAR(24) NOT NULL DEFAULT 'private',
    share_token VARCHAR(96) UNIQUE,
    start_collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE RESTRICT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_worlds_owner ON worlds(owner_id, updated_at);

CREATE TABLE world_boards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world_id VARCHAR(64) NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_world_board UNIQUE (world_id, collection_id)
);

CREATE INDEX idx_world_boards_collection ON world_boards(collection_id);

