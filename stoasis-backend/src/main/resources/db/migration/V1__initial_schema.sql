CREATE TABLE users (
    id VARCHAR(64) PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    avatar_url VARCHAR(2048),
    plan VARCHAR(32) NOT NULL DEFAULT 'free',
    password_hash VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deletion_scheduled_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE collections (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    emoji VARCHAR(32) NOT NULL,
    owner_id VARCHAR(64) NOT NULL REFERENCES users(id),
    visibility VARCHAR(24) NOT NULL,
    invite_token VARCHAR(96) UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE collection_allowed_types (
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    pin_type VARCHAR(24) NOT NULL,
    PRIMARY KEY (collection_id, pin_type)
);

CREATE TABLE collection_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    user_id VARCHAR(64) NOT NULL REFERENCES users(id),
    role VARCHAR(24) NOT NULL,
    CONSTRAINT uk_collection_member UNIQUE (collection_id, user_id)
);

CREATE INDEX idx_collection_members_user ON collection_members(user_id);

CREATE TABLE pins (
    id VARCHAR(64) PRIMARY KEY,
    collection_id VARCHAR(64) NOT NULL REFERENCES collections(id) ON DELETE CASCADE,
    type VARCHAR(24) NOT NULL,
    created_by VARCHAR(64) NOT NULL REFERENCES users(id),
    sort_order INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    url VARCHAR(4096),
    title VARCHAR(1000),
    description CLOB,
    image_url VARCHAR(4096),
    site_name VARCHAR(512),
    reading_time_min INTEGER,
    parse_status VARCHAR(24),
    content CLOB,
    note_color VARCHAR(24),
    file_key VARCHAR(255),
    caption VARCHAR(2000),
    image_width INTEGER,
    image_height INTEGER
);

CREATE INDEX idx_pins_collection ON pins(collection_id, sort_order);

CREATE TABLE pin_tags (
    pin_id VARCHAR(64) NOT NULL REFERENCES pins(id) ON DELETE CASCADE,
    tag VARCHAR(120) NOT NULL,
    PRIMARY KEY (pin_id, tag)
);

CREATE TABLE pin_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pin_id VARCHAR(64) NOT NULL REFERENCES pins(id) ON DELETE CASCADE,
    author_id VARCHAR(64) NOT NULL REFERENCES users(id),
    body CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_pin_comments_pin ON pin_comments(pin_id, created_at);

CREATE TABLE tags (
    id VARCHAR(64) PRIMARY KEY,
    owner_id VARCHAR(64) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    CONSTRAINT uk_tag_owner_name UNIQUE (owner_id, name)
);

CREATE TABLE uploads (
    id VARCHAR(96) PRIMARY KEY,
    owner_id VARCHAR(64) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    original_name VARCHAR(512) NOT NULL,
    content_type VARCHAR(160) NOT NULL,
    content BLOB NOT NULL,
    image_width INTEGER NOT NULL,
    image_height INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE magic_link_tokens (
    token VARCHAR(96) PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE
);
